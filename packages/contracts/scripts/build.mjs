// Compiles src/**/*.sol with solc-js (no Foundry needed) and writes:
//   artifacts/<Contract>.json      abi + bytecode (gitignored)
//   ts/abis.generated.ts           ABIs as const, for viem
//   ts/bytecode.generated.ts       creation bytecode, for deploy scripts and tests
// Foundry users can still run `forge build` / `forge test` with foundry.toml; both read the same sources.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NODE_MODULES = [join(root, 'node_modules'), join(root, '..', '..', 'node_modules')];
const OURS = ['PersonhoodRegistry', 'ReceiptsResolver', 'PayoutDistributor', 'ReceiptsReputation', 'ReceiptsGovernanceToken', 'ReceiptsGovernor', 'MockUSDC'];

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.sol') ? [p] : [];
  });
}

const sources = {};
for (const file of walk(join(root, 'src'))) {
  sources[relative(root, file).split(sep).join('/')] = { content: readFileSync(file, 'utf8') };
}

function findImports(path) {
  if (path.startsWith('src/')) return { contents: readFileSync(join(root, path), 'utf8') };
  for (const nm of NODE_MODULES) {
    const p = join(nm, path);
    if (existsSync(p)) return { contents: readFileSync(p, 'utf8') };
  }
  return { error: `File not found: ${path}` };
}

const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'cancun',
    outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] } },
  },
};

console.log(`solc ${solc.version()}: compiling ${Object.keys(sources).length} files`);
const output = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }));
const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
for (const w of (output.errors ?? []).filter((e) => e.severity !== 'error')) {
  if (!w.sourceLocation?.file?.startsWith('src/')) continue;
  console.warn(w.formattedMessage);
}
if (errors.length) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

mkdirSync(join(root, 'artifacts'), { recursive: true });
const abis = [];
const bytecodes = [];
for (const [file, contracts] of Object.entries(output.contracts)) {
  for (const [name, c] of Object.entries(contracts)) {
    if (!OURS.includes(name) || !file.startsWith('src/')) continue;
    const bytecode = `0x${c.evm.bytecode.object}`;
    writeFileSync(join(root, 'artifacts', `${name}.json`), JSON.stringify({ contractName: name, sourceName: file, abi: c.abi, bytecode }, null, 2));
    abis.push(`export const ${name}Abi = ${JSON.stringify(c.abi, null, 2)} as const;\n`);
    bytecodes.push(`export const ${name}Bytecode = '${bytecode}' as const;\n`);
    console.log(`  ${name}: ${(bytecode.length - 2) / 2} bytes`);
  }
}

const header = '// Generated by scripts/build.mjs from src/**/*.sol. Do not edit by hand.\n\n';
mkdirSync(join(root, 'ts'), { recursive: true });
writeFileSync(join(root, 'ts', 'abis.generated.ts'), header + abis.join('\n'));
writeFileSync(join(root, 'ts', 'bytecode.generated.ts'), header + bytecodes.join('\n'));
console.log('wrote ts/abis.generated.ts and ts/bytecode.generated.ts');
